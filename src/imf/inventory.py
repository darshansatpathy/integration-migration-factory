"""Interface inventory: what the estate contains, how hard each flow is, and the order to migrate it.

Complexity is a transparent weighted score, so the ranking can be argued with line by line:

| Factor | Points |
|---|---|
| base | 1 |
| fixed-width or XML at either end | 2 each |
| each transform step | 0.5 |
| date conversion | +0.5 |
| arithmetic (`multiply`) | +2 |
| filter | 1 |
| each upstream dependency | 1 |
| confidential data | 1 |
| HTTPS (API) target | 1 |

Waves follow the dependency graph: a flow migrates in the wave after the last flow it depends on,
so a downstream flow never runs on Kafka while its upstream still runs on the legacy platform
with different behaviour. Within a wave, simpler flows go first.
"""

from __future__ import annotations

from dataclasses import dataclass

from imf.model import Estate, EstateError, Flow

TIERS = [(6.0, "low"), (10.0, "medium")]


@dataclass(frozen=True)
class Entry:
    flow: Flow
    score: float
    tier: str
    wave: int
    transforms: int
    reasons: tuple[str, ...]


def score(flow: Flow) -> tuple[float, list[str]]:
    points, reasons = 1.0, []
    for end, label in ((flow.source, "source"), (flow.target, "target")):
        if end.format in ("fixed-width", "xml"):
            points += 2
            reasons.append(f"{end.format} {label}")
    steps = [s for m in flow.fields for s in m.steps]
    points += 0.5 * len(steps)
    dates = sum(s.startswith("date:") for s in steps)
    points += 0.5 * dates
    if dates:
        reasons.append(f"{dates} date conversion{'s' if dates > 1 else ''}")
    if any(s.startswith("multiply:") for s in steps):
        points += 2
        reasons.append("arithmetic")
    if flow.filter:
        points += 1
        reasons.append("filter")
    if flow.depends_on:
        points += len(flow.depends_on)
        reasons.append(f"{len(flow.depends_on)} upstream")
    if flow.classification == "confidential":
        points += 1
        reasons.append("confidential")
    if flow.target.protocol == "https":
        points += 1
        reasons.append("API target")
    return points, reasons


def waves(estate: Estate) -> dict[str, int]:
    wave: dict[str, int] = {}
    visiting: set[str] = set()

    def visit(fid: str, path: tuple[str, ...]) -> int:
        if fid in wave:
            return wave[fid]
        if fid in visiting:
            raise EstateError("dependency cycle: " + " -> ".join((*path, fid)))
        visiting.add(fid)
        w = 1 + max((visit(d, (*path, fid)) for d in estate.flows[fid].depends_on), default=0)
        visiting.discard(fid)
        wave[fid] = w
        return w

    for fid in estate.flows:
        visit(fid, ())
    return wave


def build(estate: Estate) -> list[Entry]:
    w = waves(estate)
    out = []
    for f in estate.flows.values():
        s, reasons = score(f)
        tier = next((t for limit, t in TIERS if s < limit), "high")
        out.append(Entry(f, s, tier, w[f.id], sum(len(m.steps) for m in f.fields), tuple(reasons)))
    return sorted(out, key=lambda e: (e.wave, e.score, e.flow.id))


def mermaid(entries: list[Entry]) -> str:
    lines = ["flowchart LR"]
    for e in entries:
        lines.append(
            f'  {e.flow.id.replace("-", "_")}["{e.flow.id}<br/>{e.flow.source.system} → {e.flow.target.system}<br/>wave {e.wave}, {e.tier}"]'
        )
    for e in entries:
        for d in e.flow.depends_on:
            lines.append(f"  {d.replace('-', '_')} --> {e.flow.id.replace('-', '_')}")
    return "\n".join(lines)


def markdown(entries: list[Entry]) -> str:
    systems = sorted({s for e in entries for s in (e.flow.source.system, e.flow.target.system)})
    lines = [
        "# Interface inventory",
        "",
        f"{len(entries)} flows between {len(systems)} systems ({', '.join(systems)}), in {max(e.wave for e in entries)} migration waves. "
        "Generated by `imf inventory` from `estate/`; the scoring is documented in `src/imf/inventory.py`.",
        "",
        "| Wave | Flow | Name | Source → target | Formats | Owner | Transforms | Score | Tier | Why |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for e in entries:
        f = e.flow
        lines.append(
            f"| {e.wave} | {f.id} | {f.name} | {f.source.system} → {f.target.system} | {f.source.format} → {f.target.format} | "
            f"{f.owner} | {e.transforms} | {e.score:g} | {e.tier} | {', '.join(e.reasons) or '-'} |"
        )
    lines += ["", "## Dependencies", "", "```mermaid", mermaid(entries), "```", "", "## Waves", ""]
    for w in sorted({e.wave for e in entries}):
        members = [e for e in entries if e.wave == w]
        lines.append(f"- **Wave {w}** ({sum(x.score for x in members):g} points): " + ", ".join(f"{e.flow.id} ({e.tier})" for e in members))
    lines += ["", "## Systems", "", "| System | Sends | Receives |", "|---|---|---|"]
    for s in systems:
        sends = [e.flow.id for e in entries if e.flow.source.system == s]
        recv = [e.flow.id for e in entries if e.flow.target.system == s]
        lines.append(f"| {s} | {', '.join(sends) or '-'} | {', '.join(recv) or '-'} |")
    return "\n".join(lines) + "\n"


def as_rows(entries: list[Entry]) -> list[dict[str, object]]:
    return [
        {
            "wave": e.wave,
            "flow": e.flow.id,
            "name": e.flow.name,
            "domain": e.flow.domain,
            "owner": e.flow.owner,
            "source": f"{e.flow.source.system}:{e.flow.source.format}",
            "target": f"{e.flow.target.system}:{e.flow.target.format}",
            "schedule": e.flow.schedule,
            "classification": e.flow.classification,
            "transforms": e.transforms,
            "depends_on": ";".join(e.flow.depends_on),
            "score": e.score,
            "tier": e.tier,
            "topic": e.flow.topic,
        }
        for e in entries
    ]
